// Run inside the real page with agent-browser eval --stdin. No app internals.
(async () => {
  const checks=[];
  const $=s=>document.querySelector(s), $$=s=>[...document.querySelectorAll(s)];
  const assert=(condition,message)=>{if(!condition)throw new Error(message);};
  const wait=async predicate=>{const end=Date.now()+12000;while(!predicate()){if(Date.now()>end)throw new Error('UI did not become ready');await new Promise(r=>setTimeout(r,80));}};
  const ready=()=>$('#loading').hidden&&$('#error').hidden&&!$('#play').disabled;
  const change=async(selector,value)=>{const el=$(selector);el.value=value;el.dispatchEvent(new Event('change',{bubbles:true}));await wait(ready);};
  const seek=value=>{const el=$('#scrubber');el.value=value;el.dispatchEvent(new Event('input',{bubbles:true}));};
  const game=async pane=>{const id=$(`[data-pane="${pane}"] .episode`).value;return(await fetch(`/api/episode?id=${id}`)).json();};
  const pass=(name,evidence)=>checks.push({name,status:'pass',evidence});
  await wait(ready);
  assert($$('.community').length===1,'Start on a single default recorded community');
  const human=await game(0);
  assert(human.launch_id==='67430636'&&human.condition==='Equal Baseline Exp 1','Wrong median default');
  assert($('.episode').options.length===40,'Missing human episodes');
  pass('default selection',{key:[human.condition,human.launch_id,human.episode_id],episodes:40});
  const first=human.rounds[0];
  const cells=$$('.exact-values tr')[0].querySelectorAll('td');
  assert(cells[1].textContent===first.raw.offer_0&&cells[3].textContent===first.raw.player_reward_0,'Source precision lost');
  $('[data-resident="2"]').click();assert($('.resident-name').textContent==='Resident C','Resident click failed');
  assert($('.resident-values dd:nth-of-type(1)')!==null,'Resident values absent');
  seek(39);const finalCells=$$('.exact-values tr')[2].querySelectorAll('td');
  assert(Number(finalCells[4].textContent)===human.rounds[39].cumulative_surplus[2],'Final cumulative drift');
  seek(11);assert($('.active-count').textContent==='0 / 4','Below-one opportunities wrong');
  assert($('.exact-pool').textContent.includes(human.rounds[11].pool_after_raw),'Recorded floor was replaced');
  seek(0);assert(Number($$('.exact-values tr')[2].querySelectorAll('td')[4].textContent)===first.cumulative_surplus[2],'Backward seek accumulated totals');
  pass('resident, exact values and backward seek',{resident:'C',final_cumulative:human.rounds[39].cumulative_surplus[2],round12_after:human.rounds[11].pool_after});
  await change('#speed','4');$('#play').click();await wait(()=>Number($('#scrubber').value)>=1);$('#play').click();
  const paused=$('#scrubber').value;await new Promise(r=>setTimeout(r,500));assert($('#scrubber').value===paused,'Pause failed');
  assert($('#play').getAttribute('aria-label')==='Play','Pause label wrong');
  $('#previous').click();assert(Number($('#scrubber').value)===Number(paused)-1,'Previous round failed');
  $('#restart').click();assert($('#scrubber').value==='0','Restart failed');
  pass('play, pause, speed, previous and restart',{paused_round:Number(paused)+1});
  await change('.cohort','bc1');assert($('.episode').options.length===512,'Missing BC1 episodes');
  const bc=await game(0);seek(39);assert($('.pool-after').textContent==='N/A','Final BC1 after pool invented');
  assert($('.source-badge').textContent.includes('UPSTREAM MODEL'),'Model provenance absent');
  pass('upstream replay',{key:[bc.condition,bc.launch_id,bc.episode_id],final_after:bc.rounds[39].pool_after,episodes:512});
  $('#compare').click();await wait(ready);assert($$('.community').length===2,'Comparison absent');
  await change('[data-pane="1"] .mechanism','Mixed');seek(8);
  assert($$('.after-source').every(e=>e.textContent.includes('Source round 8')),'Clocks not synchronized');
  assert($('#mode-context').textContent.includes('Different observed groups'),'Counterfactual limit missing');
  pass('independent recorded comparison',{round:9,keys:$$('.identity').map(e=>e.textContent)});
  $('.outcome-detail summary').click();const point=$('.scatter [role="button"]');point.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}));await wait(ready);
  assert($('#scrubber').value==='0','Outcome selection did not reset');pass('keyboard outcome selection',{selected:$('.episode').value});
  $('#sandbox-mode').click();await wait(ready);
  const qs=p=>$$(`[data-pane="${p}"] .fractions input`).map(e=>e.value);
  assert(JSON.stringify(qs(0))===JSON.stringify(qs(1)),'Comparison fractions not matched on entry');
  assert($$('.source-badge').every(e=>e.textContent==='NEW SCRIPTED SIMULATION'),'Scripted provenance wrong');
  seek(2);await change('[data-pane="0"] .sandbox-mechanism','proportional');
  assert($('#scrubber').value==='0'&&$('[data-pane="0"] .pool-before').textContent==='200','Rule edit spliced future');
  await change('[data-pane="0"] .fractions input','0');$('#next').click();
  assert($('[data-pane="0"] .active-count').textContent==='3 / 4','Proportional zero-return opportunity wrong');
  assert($('[data-pane="1"] .fractions input').value==='0.75','Explicit pane edit altered other pane');
  $('[data-pane="0"] .reset-sandbox').click();await wait(ready);
  assert($('[data-pane="0"] .sandbox-mechanism').value==='equal'&&$('#scrubber').value==='0','Sandbox reset failed');
  await change('[data-pane="0"] .fractions input','0.58');
  assert($$('.exact-values tr')[0].querySelectorAll('td')[2].textContent==='29','Decimal policy boundary incorrect');
  pass('scripted policies, matched comparison, edits and reset',{rules:['equal','proportional'],decimal_fraction:0.58,initial_return:29});
  for(const input of $$('[data-pane="0"] .fractions input')){input.value='0';input.dispatchEvent(new Event('change',{bubbles:true}));await wait(ready);}
  assert($('[data-pane="0"] .identity').textContent.includes('exact-zero pool'),'Exact-zero termination not shown');
  $('#next').click();assert($('[data-pane="0"] .end-state').textContent.includes('final state held'),'Short run not held explicitly');
  $('#reduced-motion').click();assert($('#reduced-motion').checked,'Reduced motion failed');
  pass('unequal run lengths and reduced motion',{ended:$('.end-state').textContent});
  assert($('#error').hidden,'Visible error');
  window.evopolisBrowserVerification={viewport:[innerWidth,innerHeight],checks};
  return window.evopolisBrowserVerification;
})()
